/**
 * Internacionalização — pura, sem React, partilhada pelo core e pela UI.
 *
 * Regra: o core NUNCA formata texto para o utilizador. Guarda uma CHAVE + params
 * (ex.: notícias) e a UI traduz no momento de desenhar, com o idioma escolhido.
 * Assim, trocar de idioma reescreve tudo (incluindo o feed de notícias) na hora.
 *
 * Interpolação: "{param}" é substituído. Um param cujo valor comece por "@" é ele
 * próprio uma chave a traduzir (aninhamento), opcionalmente com params:
 *   "@cup.prelim|n=3"  →  traduz cup.prelim com { n: 3 }.
 */

export type Lang = 'pt-PT' | 'pt-BR' | 'en';
export const LANGS: Lang[] = ['pt-PT', 'pt-BR', 'en'];
export const LANG_LABELS: Record<Lang, string> = {
  'pt-PT': 'Português (PT)',
  'pt-BR': 'Português (BR)',
  en: 'English',
};

export type MsgParams = Record<string, string | number>;

/** Descritor de mensagem gerado pelo core (notícias, feedback). */
export interface Msg {
  key: string;
  params?: MsgParams;
}

export function translate(lang: Lang, key: string, params?: MsgParams): string {
  const table = DICT[lang] ?? DICT['pt-PT'];
  let s = table[key] ?? DICT['pt-PT'][key] ?? key;
  if (params) {
    for (const [k, raw] of Object.entries(params)) {
      let val = String(raw);
      if (val.startsWith('@')) {
        const [nk, ...segs] = val.slice(1).split('|');
        const np: MsgParams = {};
        for (const seg of segs) {
          const eq = seg.indexOf('=');
          if (eq > 0) np[seg.slice(0, eq)] = seg.slice(eq + 1);
        }
        val = translate(lang, nk!, np);
      }
      s = s.split(`{${k}}`).join(val);
    }
  }
  return s;
}

/** Traduz um descritor de mensagem do core. */
export function tMsg(lang: Lang, msg: Msg): string {
  return translate(lang, msg.key, msg.params);
}

